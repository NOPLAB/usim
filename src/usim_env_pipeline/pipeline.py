"""End-to-end CPU point-cloud archival, reconstruction and streaming-map generation."""

from __future__ import annotations

from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict
import json
import os
from pathlib import Path

from .models import MapConfig, PipelineInputError, Source, SourceMetadata, Summary
from .regions import RegionJob, region_job
from .storage import archive_source, partition, write_json
from .usd import LayerMetadata, make_layers


def generate(source: Source, output: Path, config: MapConfig = MapConfig()) -> Summary:
    """Reconstruct a map; archive references separately, never implicitly fuse frames."""
    output = output.resolve()
    inputs = (source, *config.references)
    if len({item.key for item in inputs}) != len(inputs):
        raise PipelineInputError('Source keys must be unique')
    if len({item.path.name for item in inputs}) != len(inputs):
        raise PipelineInputError('Source basenames must be unique')
    existing = output.exists() and any(output.iterdir())
    if existing and not config.resume:
        raise PipelineInputError('Output must be absent or empty; use a new map directory')
    for folder in ('source', 'records', 'meshes', 'points', 'reports'):
        (output / folder).mkdir(parents=True, exist_ok=True)
    if existing:
        from .resume import validate

        validate(output, source, config)
        cached = json.loads((output / 'manifest.json').read_text(encoding='utf-8'))
        if cached['status'] == 'complete':
            return json.loads((output / 'summary.json').read_text(encoding='utf-8'))
        provenance = cached['sources']
        records_count = cached['records']
        color = cached['color']
        keys = [
            tuple(int(v.replace('m', '-')) - 10000 for v in file.stem[2:].split('_'))
            for file in output.joinpath('records').glob('t_*.npz')
        ]
        occupied = frozenset((key[0], key[1]) for key in keys)
        if len(occupied) != cached['occupied_tiles']:
            raise PipelineInputError('Regional archive set changed')
    else:
        primary = archive_source(source, output)
        primary.metadata['role'] = 'primary'
        provenance: dict[str, SourceMetadata] = {source.key: primary.metadata}
        for reference in config.references:
            archived = archive_source(reference, output)
            archived.metadata['role'] = 'unfused reference'
            provenance[reference.key] = archived.metadata
        occupied = partition(primary, output, config.tile_size)
        records_count = len(primary.records)
        color = primary.color_description
        del primary
    metadata = LayerMetadata(
        source.license,
        source.attribution,
        source.catalog,
        config.frame,
        color,
    )
    manifest = {
        'schema': 1,
        'pipeline': 'usim_env_pipeline',
        'status': 'generating',
        'license': source.license,
        'attribution': source.attribution,
        'source_catalog': source.catalog,
        'sources': provenance,
        'primary_source': source.key,
        'tile_size': config.tile_size,
        'halo': config.halo,
        'support': asdict(config.support),
        'frame': config.frame,
        'units': 'meters',
        'up_axis': 'Z',
        'color': color,
        'records': records_count,
        'occupied_tiles': len(occupied),
        'normal_policy': config.normal_policy,
        'method': 'CPU Open3D ball pivoting, normalized working plane normals',
        'working_normal_orientation': 'largest absolute component positive; XYZ tie order',
        'working_positions': 'float32 XYZ; original records and source bytes retained',
        'rendering': 'all source points plus supported triangle surfaces; no point omission',
        'ownership': 'half-open XY face-centroid core; source-order normal-preserving input',
        'unsupported': 'open gaps remain; no invented ground, extrusion or filling',
    }
    write_json(output / 'manifest.json', manifest)
    (output / 'NOTICE').write_text(
        'Derived point-cloud map generated by usim_env_pipeline (MIT software).\n'
        'Software licensing does not relicense source data or derived maps.\n'
        f'Primary data license: {source.license}\n'
        f'Attribution: {source.attribution}\nSource catalog: {source.catalog}\n'
        + ''.join(
            f'Source {item.key}: {item.url or item.path.name}; license {item.license}; '
            f'attribution {item.attribution}\n'
            for item in inputs
        )
        + 'Changes: regional partitioning, supported triangles with source-derived XYZ,\n'
        'float32 display/mesh coordinates, source RGB/intensity or constant-gray display.\n'
        f'Working normal policy: {config.normal_policy}; estimated normals are derived,\n'
        'not measured. Original files/PCD fields remain unchanged. References are\n'
        'archive-only, not fused. No CRS, survey accuracy, watertightness, unseen\n'
        'surfaces, or gap filling is asserted. See manifest.json and summary.json.\n',
        encoding='utf-8',
    )
    print(f'ARCHIVED records={records_count} tiles={len(occupied)}', flush=True)
    jobs = [RegionJob(output, key, occupied, config, metadata) for key in sorted(occupied)]
    # Set these before spawning/importing native CPU libraries in workers.
    os.environ['OMP_NUM_THREADS'] = '1'
    os.environ['OPENBLAS_NUM_THREADS'] = '1'
    reports = []
    if existing:
        from .resume import completed

        pending = []
        for job in jobs:
            report = completed(job)
            if report is None:
                pending.append(job)
            else:
                reports.append(report)
        jobs = pending
        print(f'RESUME completed={len(reports)} pending={len(jobs)}', flush=True)
    with ProcessPoolExecutor(max_workers=config.workers) as executor:
        for report in executor.map(region_job, jobs, chunksize=1):
            reports.append(report)
            if len(reports) % 25 == 0:
                print(
                    f'PROGRESS tiles={len(reports)}/{len(occupied)} '
                    f'triangles={sum(r["triangles"] for r in reports)}',
                    flush=True,
                )
    reports.sort(key=lambda report: report['key'])
    make_layers(output, reports, metadata)
    summary: Summary = {
        'records': sum(r['records'] for r in reports),
        'normal_valid': sum(r['normal_valid'] for r in reports),
        'normal_invalid': sum(r['normal_invalid'] for r in reports),
        'triangles': sum(r['triangles'] for r in reports),
        'mesh_vertices': sum(r['mesh_vertices'] for r in reports),
        'core_meshed_records': sum(r['core_meshed_records'] for r in reports),
        'unmeshed_records': sum(r['unmeshed_records'] for r in reports),
        'horizontal_triangles': sum(r['horizontal_triangles'] for r in reports),
        'other_triangles': sum(r['other_triangles'] for r in reports),
        'open_boundary_edges': sum(r['open_boundary_edges'] for r in reports),
        'nonmanifold_edges': sum(r['nonmanifold_edges'] for r in reports),
        'rejected_support': sum(r['rejected_support'] for r in reports),
        'estimated_normal_records': sum(r['estimated_normal_records'] for r in reports),
        'occupied_tiles': len(reports),
        'meshed_tiles': sum(bool(r['triangles']) for r in reports),
        'unmeshed_tiles': [r['name'] for r in reports if not r['triangles']],
    }
    write_json(output / 'summary.json', summary)
    manifest['status'] = 'complete'
    write_json(output / 'manifest.json', manifest)
    print('GENERATION_PASSED ' + json.dumps(summary), flush=True)
    return summary
